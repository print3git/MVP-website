#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

function toYaml(obj, indent = 0) {
  const pad = '  '.repeat(indent);
  if (Array.isArray(obj)) {
    return obj
      .map(item => pad + '- ' + toYaml(item, indent + 1).trimStart())
      .join('\n');
  }
  if (obj && typeof obj === 'object') {
    return Object.entries(obj)
      .map(([key, value]) => {
        const valueYaml = toYaml(value, indent + 1);
        if (typeof value === 'object' && value !== null) {
          return pad + key + ':\n' + valueYaml;
        }
        return pad + key + ': ' + valueYaml.trim();
      })
      .join('\n');
  }
  return String(obj);
}

const repoRoot = path.resolve(__dirname, '../..');
process.chdir(repoRoot);

/** Utility to add a job if its name is unique */
const jobs = [];
function addJob(job) {
  if (!jobs.find(j => j.name === job.name)) {
    jobs.push({
      name: job.name,
      command: job.command,
      paths: job.paths || [],
      needs: job.needs || []
    });
  }
}

// List all tracked files once to avoid repeated shelling out
const allFiles = execSync('git ls-files', { encoding: 'utf8' })
  .split('\n')
  .filter(Boolean);

// Scan package.json files for test scripts
const packageJsonFiles = allFiles.filter(f => f.endsWith('package.json') && !f.includes('node_modules'));
for (const pkgPath of packageJsonFiles) {
  const dir = path.dirname(pkgPath);
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
  const scripts = pkg.scripts || {};
  for (const [scriptName] of Object.entries(scripts)) {
    if (scriptName === 'test' || scriptName.startsWith('test')) {
      const jobName = `${dir === '.' ? 'root' : dir.replace(/\//g, '-')}:${scriptName}`;
      const command = dir === '.' ? `npm run ${scriptName}` : `npm run ${scriptName} --prefix ${dir}`;
      addJob({ name: jobName, command, paths: [dir] });
    }
  }
}

// Detect common test config files
for (const file of allFiles) {
  if (/jest\.config\.[cm]?js$/.test(file)) {
    addJob({ name: `jest:${path.dirname(file)}`, command: 'npm test', paths: [file] });
  } else if (/playwright\.config\.[cm]?js$/.test(file)) {
    addJob({ name: `playwright:${path.dirname(file)}`, command: 'npx playwright test', paths: [file] });
  } else if (/vitest\.config\.[cm]?js$/.test(file)) {
    addJob({ name: `vitest:${path.dirname(file)}`, command: 'npx vitest run', paths: [file] });
  }
}

// Detect jobs that existed in the previous commit but are missing now
const workflowFiles = allFiles.filter(f => f.startsWith('.github/workflows/') && f.endsWith('.yml'));
const currentJobNames = new Set(jobs.map(j => j.name));

for (const wf of workflowFiles) {
  try {
    const prev = execSync(`git show HEAD~1:"${wf}"`, { encoding: 'utf8' });
    const lines = prev.split(/\r?\n/);
    let current = null;
    let command = null;
    for (const line of lines) {
      const jobMatch = line.match(/^  ([\w-]+):\s*$/);
      if (jobMatch) {
        if (current && !currentJobNames.has(current)) {
          addJob({ name: current, command: command || `echo "historical job ${current}"`, paths: [] });
          currentJobNames.add(current);
        }
        current = jobMatch[1];
        command = null;
        continue;
      }
      if (current) {
        const runMatch = line.match(/run:\s*(.*)/);
        if (runMatch && !command) {
          command = runMatch[1].trim();
        }
        if (/^\S/.test(line)) {
          if (!currentJobNames.has(current)) {
            addJob({ name: current, command: command || `echo "historical job ${current}"`, paths: [] });
            currentJobNames.add(current);
          }
          current = null;
          command = null;
        }
      }
    }
    if (current && !currentJobNames.has(current)) {
      addJob({ name: current, command: command || `echo "historical job ${current}"`, paths: [] });
    }
  } catch {
    // ignore missing files
  }
}

// Ensure output directory exists
const outDir = path.join(repoRoot, 'ci', 'generated');
fs.mkdirSync(outDir, { recursive: true });

// Write JSON
const jsonPath = path.join(outDir, 'full-ci.jobs.json');
fs.writeFileSync(jsonPath, JSON.stringify(jobs, null, 2) + '\n');

// Build composite workflow YAML
const matrix = jobs.map(j => ({ name: j.name, command: j.command }));
const workflow = {
  name: 'Full CI',
  on: { workflow_call: {} },
  jobs: {
    test: {
      name: '${{ matrix.name }}',
      'runs-on': 'ubuntu-latest',
      strategy: { 'fail-fast': false, matrix: { include: matrix } },
      steps: [
        { uses: 'actions/checkout@v4' },
        { run: '${{ matrix.command }}' }
      ]
    }
  }
};

const yamlPath = path.join(outDir, 'full-ci.yml');
fs.writeFileSync(
  yamlPath,
  '# Generated by scripts/ci/discover-and-restore-tests.js\n' + toYaml(workflow) + '\n'
);

console.log(`Wrote ${jobs.length} jobs to ${jsonPath}`);
